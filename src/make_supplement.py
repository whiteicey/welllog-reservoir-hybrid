"""Generate the supplementary report: experiment registry, per-well scores by generation, per-test-well
prediction statistics, feature lists, timing. Writes outputs/supplement/*.csv and outputs/supplement/supplement.md.
"""
from __future__ import annotations
import glob
import json
from pathlib import Path

import numpy as np
import pandas as pd

from harness import load_or_build_cache, acc_vec, default_mask, BOUNDS, V2_CAL, N_FOLDS, total

OUT = Path("outputs/supplement"); OUT.mkdir(parents=True, exist_ok=True)
C = load_or_build_cache(Path("data"), Path("cache"))
y, wells, folds = C["tr_y"], C["tr_well"], C["tr_fold"]
train_ids = C["meta"]["train_wells"]; test_ids = C["meta"]["test_wells"]
T = ("POR", "PERM", "SW")
md = ["# Supplementary material (auto-generated by make_supplement.py)", ""]

# ---------------- 1. experiment registry ----------------
rows = []
for p in sorted(glob.glob("outputs/*/report.json")):
    name = p.split("/")[1]; r = json.load(open(p)); a = r.get("args", {})
    row = {"experiment": name, "kind": "", "target": a.get("target", ""), "features": a.get("features", ""), "model": a.get("model", ""),
           "bins": a.get("bins", ""), "seeds": a.get("seeds", ""), "key_metric": "", "value": "", "vs_v2": "", "ci95": "", "gpu_seconds": ""}
    if "nondefault_only" in r:
        row["kind"] = "catboost variant"; k = "utility" if "utility" in r["nondefault_only"] else "point"
        row["key_metric"] = "full score (v2 gate) / joint"; row["value"] = f"{r['full_v2gate'][k]['micro']:.5f} / {r.get('joint_full', {}).get('micro', float('nan')):.5f}"
        row["vs_v2"] = f"{r['full_v2gate'][k]['micro'] - r['full_v2gate']['v2']['micro']:+.5f}"
        if "joint_full" in r: row["ci95"] = str([round(x, 5) for x in r["joint_full"]["paired_vs_v2"]["ci95"]])
        row["gpu_seconds"] = int(sum(f["seconds"] for f in r["folds"]))
    elif "gate" in r and "args" in r:
        row["kind"] = "gate variant"; row["key_metric"] = "gate acc@0.5 (v2 -> new)"; row["value"] = f"{r['gate']['v2_gate_acc_at_v2th']:.4f} -> {r['gate']['new_gate_acc_at_0.5']:.4f}"
        row["gpu_seconds"] = int(sum(f["seconds"] for f in r["folds"]))
    elif "TOTAL" in r and isinstance(r["TOTAL"], dict) and "nn" in r["TOTAL"]:
        row["kind"] = "sequence net"; row["key_metric"] = "total alone / gate acc POR,PERM,SW"; row["value"] = f"{r['TOTAL']['nn']:.3f} / " + ",".join(f"{r[t]['gate_acc']['nn@0.5']:.3f}" for t in T)
        row["features"] = "curves" + ("+113 base" if a.get("use_base") in ("1", "True", True) else ""); row["seeds"] = a.get("seeds", ""); row["gpu_seconds"] = int(sum(f["seconds"] for f in r["log"]))
    elif "state_accuracy_argmax" in r:
        row["kind"] = "4-state model"; row["key_metric"] = "state acc / POR,PERM,SW nested"; row["value"] = f"{r['state_accuracy_argmax']:.4f} / " + ",".join(f"{r['raw'][t + '_state']['nested_score']:.4f}" for t in T)
    elif "TOTAL_nested" in r:
        row["kind"] = "assembly"; row["key_metric"] = "nested total / optimistic"; row["value"] = f"{r['TOTAL_nested']:.3f} / {r['TOTAL_global_selected_optimistic']:.3f}"; row["vs_v2"] = f"{r['TOTAL_nested'] - r['TOTAL_v2']:+.3f}"
    elif "state_accuracy" in r and "n_features" in r:
        row["kind"] = "level-2 stack"; row["key_metric"] = "state acc"; row["value"] = f"{r['state_accuracy']:.4f}"
    elif "TOTAL" in r and "POR" in r and isinstance(r["POR"], dict) and "micro" in r["POR"]:
        row["kind"] = "generation CV"; row["key_metric"] = "total"; row["value"] = f"{r['TOTAL']:.3f}"
    elif "CV_leave_well_out" in r:
        row["kind"] = "transfer (Volve)"; row["key_metric"] = "blind RMSE E1 / winner"; row["value"] = f"{r['E5_blind_wells']['E1_reg_no_gate']['rmse_all3']:.4f} / 0.0525"
    else:
        row["kind"] = "diagnostic"
    rows.append(row)
reg = pd.DataFrame(rows); reg.to_csv(OUT / "experiment_registry.csv", index=False)
md += ["## 1. Experiment registry", "", "All runs share the same 5 well folds (GroupKFold on 80 wells). `vs_v2` is the change of the full score against the v2 rule on the same OOF rows; `ci95` is the paired well-bootstrap interval of the joint-decoded variant.", "",
       reg.to_markdown(index=False), ""]

# ---------------- 2. per-well scores by generation ----------------
v1 = np.load("outputs/cv_v1/final_oof.npy")
V2 = np.load("outputs/cv_v2/oof.npz")
v2 = np.zeros_like(y)
for f in range(N_FOLDS):
    va = folds == f
    v2[va, 0] = np.where(V2["por_gate"][va] >= V2_CAL["POR"]["threshold"], 0.1, np.expm1(V2["por_centers"][f])[np.argmax(V2["por_prob"][va], 1)])
v2[:, 1] = np.where(V2["perm_gate"] >= V2_CAL["PERM"]["threshold"], 0.01, np.clip(10 ** (V2["perm_log"] * 1.03), *BOUNDS["PERM"]))
v2[:, 2] = np.where(V2["sw_gate"] >= V2_CAL["SW"]["threshold"], 99.9, np.clip(V2["sw_reg"] * 1.05 - 3.0, *BOUNDS["SW"]))
v3 = np.load("outputs/assembly_D/final_oof.npy")
pw = []
for w in np.unique(wells):
    m = wells == w; rec = {"well": train_ids[w][:8], "fold": int(folds[m][0]), "rows": int(m.sum()),
                           "POR_default_share": float((y[m, 0] <= 0.1).mean()), "SW_default_share": float((y[m, 2] >= 99.9).mean())}
    for g, P in (("v1", v1), ("v2", v2), ("v3", v3)):
        sc = {t: float(acc_vec(P[m, i], y[m, i], t).mean()) for i, t in enumerate(T)}
        for t in T: rec[f"{g}_{t}"] = sc[t]
        rec[f"{g}_total"] = total(sc)
    rec["v3_minus_v2"] = rec["v3_total"] - rec["v2_total"]
    pw.append(rec)
pw = pd.DataFrame(pw).sort_values("v3_minus_v2"); pw.to_csv(OUT / "per_well_scores_by_generation.csv", index=False)
md += ["## 2. Per-well out-of-fold scores by generation (80 training wells)", "",
       f"v3 beats v2 on {int((pw.v3_minus_v2 > 0).sum())} of 80 wells; median well gain {pw.v3_minus_v2.median():+.3f}, min {pw.v3_minus_v2.min():+.3f}, max {pw.v3_minus_v2.max():+.3f}.", "",
       pw.round(4).to_markdown(index=False), ""]
# fold summary
fs = []
for f in range(N_FOLDS):
    m = folds == f; rec = {"fold": f, "wells": int(len(np.unique(wells[m]))), "rows": int(m.sum())}
    for g, P in (("v1", v1), ("v2", v2), ("v3", v3)):
        rec[f"{g}_total"] = total({t: float(acc_vec(P[m, i], y[m, i], t).mean()) for i, t in enumerate(T)})
    fs.append(rec)
fs = pd.DataFrame(fs); fs.to_csv(OUT / "per_fold_scores_by_generation.csv", index=False)
md += ["### Per-fold totals", "", fs.round(3).to_markdown(index=False), ""]

# ---------------- 3. test-well prediction statistics by generation ----------------
res = {"v1": "<PROJECT_ROOT>", "v2": "<PROJECT_ROOT>", "v3": "outputs/final_v3/result.json"}
tw = []
preds = {g: {e["logId"]: pd.DataFrame(e["predictions"]) for e in json.load(open(p))["resultData"]} for g, p in res.items()}
for wid in test_ids:
    rec = {"well": wid[:8], "rows": len(preds["v3"][wid])}
    for g in res:
        d = preds[g][wid]
        rec[f"{g}_POR_default"] = float((d.POR <= 0.1).mean()); rec[f"{g}_PERM_default"] = float((d.PERM <= 0.01).mean()); rec[f"{g}_SW_default"] = float((d.SW >= 99.9).mean())
        rec[f"{g}_POR_nondef_median"] = float(d.POR[d.POR > 0.1].median()); rec[f"{g}_SW_nondef_median"] = float(d.SW[d.SW < 99.9].median())
    a, b = preds["v2"][wid], preds["v3"][wid]
    rec["v3_vs_v2_gate_disagreement_POR"] = float(((a.POR <= 0.1) != (b.POR <= 0.1)).mean()); rec["v3_vs_v2_gate_disagreement_SW"] = float(((a.SW >= 99.9) != (b.SW >= 99.9)).mean())
    tw.append(rec)
tw = pd.DataFrame(tw); tw.to_csv(OUT / "test_well_prediction_stats.csv", index=False)
md += ["## 3. Blind-well prediction statistics by generation (10 test wells; the leaderboard scores 5 of them)", "", tw.round(4).to_markdown(index=False), ""]

# ---------------- 4. feature lists ----------------
feat = {"base_113": C["meta"]["base_feature_names"], "enhanced_237": C["meta"]["enhanced_feature_names"],
        "extra_181": Path("cache/extra_names.txt").read_text().split("\n"), "alignment_17": Path("cache/aln_names.txt").read_text().split("\n")}
for k, v in feat.items():
    Path(OUT / f"features_{k}.txt").write_text("\n".join(v))
md += ["## 4. Feature sets", "", "| set | count | file |", "|---|---:|---|"] + [f"| {k} | {len(v)} | features_{k}.txt |" for k, v in feat.items()] + [""]

# ---------------- 5. decision configuration of the final system ----------------
dec = json.load(open("outputs/assembly_D/decision.json"))
md += ["## 5. Final decision configuration (assembly D, selected on all five folds)", "", "```json", json.dumps(dec, indent=1), "```", ""]

# ---------------- 6. compute budget ----------------
budget = reg[reg.gpu_seconds != ""].copy(); budget["gpu_seconds"] = budget["gpu_seconds"].astype(float)
md += ["## 6. Compute budget (H20 GPU seconds of the 5-fold runs, shared GPU; single-run wall time is 1.5-2x lower)", "",
       f"Total logged: {budget.gpu_seconds.sum() / 3600:.1f} GPU-hours over {len(budget)} runs.", "",
       budget[["experiment", "kind", "gpu_seconds"]].sort_values("gpu_seconds", ascending=False).to_markdown(index=False), ""]
(OUT / "supplement.md").write_text("\n".join(md), encoding="utf-8")
print("written", OUT, len(reg), "experiments", len(pw), "wells")
